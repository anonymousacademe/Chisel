"""Generated tables: a CSV plus a formatting spec become a table (docs/dev/plan-research-mode.md 7.4).

A table with ``source: data`` is ``tables/tbl-<label>.md`` whose YAML holds ``data: <csv path>``, an optional
``caption`` and the spec under ``format:``. No code runs: the spec is data. The body of such a note is
generated and read-only (``apply_table`` writes it, between a marker comment and the end); the author edits the
spec or the CSV.

The spec (every key optional)::

    format:
      columns:                         # order = output order; omitted = every CSV column, as is
        - Method                       # a CSV header on its own
        - key: Time                    # the CSV header
          header: Run time             # shown header (default: key)
          unit: s                      # appended to the header as "Run time (s)"
          decimals: 2                  # or  sig: 3  (significant figures)
          thousands: true              # 1,234.50
          align: decimal               # left | right | center | decimal (numbers default to right)
          best: min                    # bold the smallest (or: max); ties are all bold
          missing: "n/a"               # shown for an empty cell
      sort: {by: Time, descending: false}      # or just a header name
      spanners:                        # a header row above the columns (LaTeX form only)
        - {label: Accuracy, columns: [Train, Test]}
      footnotes: ["Mean of 5 runs."]

Three forms come out of ``build_table``: ``markdown`` (a pipe table, for the file and the editor), ``grid``
(a pandoc grid table, for Word and general conversion) and ``latex`` (booktabs, for the PDF). Pipe tables cannot
do a spanning header or decimal alignment; the grid and LaTeX forms drop what they cannot carry and every
such loss is a plain-words entry in ``warnings``, never silent. Decimal alignment is exact only for a column
with ``decimals`` (same number of decimals, right aligned); with ``sig`` it is approximated, and says so.
VERIFY with the author's real Word template how far the grid form survives into .docx.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import math
import re
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from . import fsutil, objects
