MAX_CSV_BYTES = 5 * 1024 * 1024
MAX_ROWS = 5000
MARKER = "<!-- generated by Chisel from {csv}: edit the format spec or the data, not this table -->"
_NUMBER = re.compile(r"^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?$")


@dataclass
class BuiltTable:
    markdown: str                                   # pipe table (+ footnote paragraphs), the file's body form
    grid: str = ""                                  # pandoc grid table (+ footnotes), the Word-bound form
    latex: str = ""                                 # booktabs tabular (+ footnotes), the PDF-bound form
    warnings: list[str] = field(default_factory=list)
    caption: str = ""
    footnotes: list[str] = field(default_factory=list)

    @property
    def export(self) -> dict[str, str]:
        """The richer forms keyed by what they feed: ``grid`` (docx and general) and ``latex`` (pdf, tex)."""
        return {"grid": self.grid, "latex": self.latex}


# -- numbers ---------------------------------------------------------------------------


def _number(text: str) -> float | None:
    t = (text or "").strip().replace("−", "-")
    if not _NUMBER.match(t):
        return None
    try:
        v = float(t)
    except ValueError:
        return None
    return v if math.isfinite(v) else None


def _fmt_number(v: float, decimals: int | None, sig: int | None, thousands: bool) -> str:
    if sig is not None:
        if v == 0:
            d = sig - 1
        else:
            d = sig - 1 - math.floor(math.log10(abs(v)))
        v = round(v, d)
        d = max(d, 0)
    else:
        d = decimals if decimals is not None else 0
    s = f"{v:,.{d}f}" if thousands else f"{v:.{d}f}"
    return s[1:] if s.startswith("-") and float(s.replace(",", "")) == 0 else s      # no "-0.00"


# -- escaping --------------------------------------------------------------------------

_MD_SPECIAL = re.compile(r"([\\`*_\[\]<>$])")
_LATEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
          "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def _flat(text: str) -> str:
    return " ".join(str(text).replace("\r", "").split("\n"))


def _md_data(text: str) -> str:
    """A data cell as literal Markdown text (``|`` is left to the pipe writer)."""
    return _MD_SPECIAL.sub(r"\\\1", _flat(text))


def _latex(text: str, keep_math: bool = False) -> str:
    text = _flat(text)
    if keep_math:
        out, last = [], 0
        for m in re.finditer(r"(?<!\\)\$[^$\s][^$]*?(?<!\s)\$", text):
            out.append("".join(_LATEX.get(c, c) for c in text[last:m.start()]))
            out.append(m.group(0))
            last = m.end()
        out.append("".join(_LATEX.get(c, c) for c in text[last:]))
        return "".join(out)
    return "".join(_LATEX.get(c, c) for c in text)


def _width(text: str) -> int:
    return sum(2 if unicodedata.east_asian_width(c) in "WF" else 0 if unicodedata.combining(c) else 1
               for c in text)


# -- spec ------------------------------------------------------------------------------


@dataclass
class _Col:
    key: str
    index: int
    header: str
    decimals: int | None = None
    sig: int | None = None
    thousands: bool = False
    align: str = ""
    best: str = ""
    missing: str = ""
    numeric: bool = False


def _int(value, what: str, low: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < low:
        raise ValueError(f"{what} must be a whole number of at least {low}")
    return value


def _columns(header: list[str], rows: list[list[str]], spec: dict, warnings: list[str]) -> list[_Col]:
    first: dict[str, int] = {}
    for i, h in enumerate(header):
        if h in first:
            warnings.append(f"the CSV has two columns named {h}; the first is used")
        else:
            first[h] = i
    raw = spec.get("columns")
    if raw is None:
        raw = list(first)
    if not isinstance(raw, list) or not raw:
        raise ValueError("format.columns must be a list of columns")
    cols: list[_Col] = []
    for item in raw:
        d = {"key": item} if isinstance(item, str) else item
        if not isinstance(d, dict) or not isinstance(d.get("key"), str):
            raise ValueError("each column needs a key (a CSV header)")
        key = d["key"]
        if key not in first:
            raise ValueError(f"the CSV has no column named {key}")
        c = _Col(key, first[key], _flat(str(d.get("header") or key)))
        unit = d.get("unit")
        if unit:
            c.header = f"{c.header} ({_flat(str(unit))})"
        if d.get("decimals") is not None:
            c.decimals = _int(d["decimals"], f"{key}: decimals", 0)
        if d.get("sig") is not None:
            c.sig = _int(d["sig"], f"{key}: sig", 1)
        if c.decimals is not None and c.sig is not None:
            raise ValueError(f"{key}: use decimals or sig, not both")
        c.thousands = bool(d.get("thousands", False))
        c.align = str(d.get("align") or "")
        if c.align not in ("", "left", "right", "center", "decimal"):
            raise ValueError(f"{key}: align must be left, right, center or decimal")
        c.best = str(d.get("best") or "")
        if c.best not in ("", "max", "min"):
            raise ValueError(f"{key}: best must be max or min")
        c.missing = _flat(str(d.get("missing") or ""))
        cells = [r[c.index] for r in rows if c.index < len(r) and r[c.index].strip()]
        c.numeric = bool(cells) and all(_number(x) is not None for x in cells)
        if (c.decimals is not None or c.sig is not None or c.best or c.align == "decimal") and not c.numeric:
            bad = next((x for x in cells if _number(x) is None), "")
            warnings.append(f"{key}: \"{bad}\" is not a number, so the column is shown as written")
        cols.append(c)
    return cols


def _sorted(rows: list[list[str]], header: list[str], spec: dict) -> list[list[str]]:
    sort = spec.get("sort")
    if sort is None:
        return rows
    by, desc = (sort, False) if isinstance(sort, str) else (sort.get("by"), bool(sort.get("descending")))
    if by not in header:
        raise ValueError(f"cannot sort by {by}: the CSV has no such column")
    i = header.index(by)

    def cell(r: list[str]) -> str:
        return r[i] if i < len(r) else ""

    nums = [_number(cell(r)) for r in rows if cell(r).strip()]
    numeric = all(n is not None for n in nums)

    def key(r: list[str]):
        c = cell(r).strip()
        if not c:
            return (1, 0, "")                                   # empty last, whichever the direction
        return (0, _number(c), "") if numeric else (0, 0, c.casefold())

    present = sorted((r for r in rows if cell(r).strip()), key=key, reverse=desc)
    return present + [r for r in rows if not cell(r).strip()]


def _spanners(spec: dict, cols: list[_Col]) -> list[tuple[str, int, int]]:
    raw = spec.get("spanners") or []
    if not isinstance(raw, list):
        raise ValueError("format.spanners must be a list")
    out = []
    keys = [c.key for c in cols]
    for s in raw:
        if not isinstance(s, dict) or not isinstance(s.get("columns"), list) or not s.get("label"):
            raise ValueError("a spanner needs a label and columns")
        try:
            idx = sorted(keys.index(k) for k in s["columns"])
        except ValueError:
            raise ValueError("a spanner names a column that is not shown") from None
        if idx != list(range(idx[0], idx[-1] + 1)):
            raise ValueError("a spanner's columns must sit next to each other")
        out.append((_flat(str(s["label"])), idx[0], idx[-1]))
    out.sort(key=lambda t: t[1])
    for a, b in zip(out, out[1:]):
        if b[1] <= a[2]:
            raise ValueError("spanners must not overlap")
    return out


# -- forms -----------------------------------------------------------------------------


def _grid(header: list[str], rows: list[list[str]], align: list[str]) -> str:
    n = len(align)
    cells = [[c.replace("|", "\\|") for c in r] for r in [header] + rows]
    widths = [max([3] + [_width(r[i]) for r in cells]) for i in range(n)]

    def pad(text: str, w: int, a: str) -> str:
        gap = w - _width(text)
        if a == "right":
            return " " * gap + text
        if a == "center":
            return " " * (gap // 2) + text + " " * (gap - gap // 2)
        return text + " " * gap

    def line(r: list[str]) -> str:
        return "| " + " | ".join(pad(r[i], widths[i], align[i]) for i in range(n)) + " |"

    plain = "+" + "+".join("-" * (w + 2) for w in widths) + "+"
    marks = []
    for w, a in zip(widths, align):
        seg = "=" * (w + 2)
        if a in ("left", "center"):
            seg = ":" + seg[1:]
        if a in ("right", "center"):
            seg = seg[:-1] + ":"
        marks.append(seg)
    out = [plain, line(cells[0]), "+" + "+".join(marks) + "+"]
    for r in cells[1:]:
        out += [line(r), plain]
    if len(cells) == 1:
        out.append(plain)
    return "\n".join(out)


def _latex_table(cols: list[_Col], header: list[str], rows: list[list[str]], bold: list[list[bool]],
                 align: list[str], spans: list[tuple[str, int, int]], notes: list[str]) -> str:
    n = len(cols)
    spec = "".join({"left": "l", "right": "r", "center": "c"}[a] for a in align)
    out = [f"\\begin{{tabular}}{{{spec}}}", "\\toprule"]
    if spans:
        # a multicolumn replaces its cells, so only one cell per span is written
        row, rules, i = [], [], 0
        for label, a, b in spans:
            row += [""] * (a - i) + [f"\\multicolumn{{{b - a + 1}}}{{c}}{{{_latex(label, True)}}}"]
            rules.append(f"\\cmidrule(lr){{{a + 1}-{b + 1}}}")
            i = b + 1
        row += [""] * (n - i)
        out.append(" & ".join(row) + " \\\\")
        out.append("".join(rules))
    out.append(" & ".join(_latex(h, True) for h in header) + " \\\\")
    out.append("\\midrule")
    for r, flags in zip(rows, bold):
        out.append(" & ".join(f"\\textbf{{{_latex(c)}}}" if b else _latex(c) for c, b in zip(r, flags)) + " \\\\")
    out.append("\\bottomrule")
    for note in notes:
        out.append(f"\\multicolumn{{{n}}}{{l}}{{\\footnotesize {_latex(note, True)}}} \\\\")
    out.append("\\end{tabular}")
    return "\n".join(out)


def format_csv(text: str, spec: dict | None, caption: str = "") -> BuiltTable:
    """The pure core of ``build_table``: CSV text and a ``format:`` mapping to a ``BuiltTable``.
    ValueError for a spec that cannot be applied or a CSV that cannot be read."""
    spec = spec if isinstance(spec, dict) else {}
    warnings: list[str] = []
    try:
        data = [r for r in csv.reader(io.StringIO(text.lstrip("﻿"), newline="")) if any(c.strip() for c in r)]
    except csv.Error as exc:
        raise ValueError(f"cannot read the CSV: {exc}") from None
    if not data:
        raise ValueError("the CSV is empty")
    if len(data) - 1 > MAX_ROWS:
        raise ValueError(f"the CSV has more than {MAX_ROWS} rows")
    header, rows = [h.strip() for h in data[0]], data[1:]
    cols = _columns(header, rows, spec, warnings)
    rows = _sorted(rows, header, spec)
    spans = _spanners(spec, cols)
    notes = spec.get("footnotes") or []
    if not isinstance(notes, list):
        raise ValueError("format.footnotes must be a list")
    notes = [_flat(str(x)) for x in notes]

    align: list[str] = []
    for c in cols:
        a = c.align or ("right" if c.numeric else "left")
        if a == "decimal":
            a = "right"
            if c.sig is not None or (c.decimals is None and c.numeric):
                warnings.append(f"{c.key}: decimal alignment is approximated by right alignment because the "
                                "numbers do not all have the same number of decimals; set decimals to fix it")
        align.append(a)

    best: dict[int, float] = {}
    for j, c in enumerate(cols):
        if c.best and c.numeric:
            vals = [v for r in rows if c.index < len(r) and (v := _number(r[c.index])) is not None]
            if vals:
                best[j] = max(vals) if c.best == "max" else min(vals)
    shown, bold = [], []
    for r in rows:
        out_row, flags = [], []
        for j, c in enumerate(cols):
            raw = r[c.index].strip() if c.index < len(r) else ""
            v = _number(raw)
            if not raw:
                out_row.append(c.missing)
            elif v is not None and (c.decimals is not None or c.sig is not None):
                out_row.append(_fmt_number(v, c.decimals, c.sig, c.thousands))
            elif v is not None and c.thousands:
                mantissa = re.split("[eE]", raw)[0]
                out_row.append(_fmt_number(v, len(mantissa.split(".")[1]) if "." in mantissa else 0, None, True))
            else:
                out_row.append(raw)
            flags.append(j in best and v is not None and v == best[j])
        shown.append(out_row)
        bold.append(flags)
    headers = [c.header for c in cols]

    md_rows = [[(f"**{_md_data(x)}**" if b and x else _md_data(x)) for x, b in zip(r, f)]
               for r, f in zip(shown, bold)]
    md_head = [_flat(h) for h in headers]
    foot = "".join(f"\n\n{n}" for n in notes)
    markdown = to_pipe(Table([md_head] + md_rows, align)) + foot
    if spans:
        warnings.append("a spanning header cannot be shown in a Markdown or Word table; it is kept in the PDF "
                        "(LaTeX) form only")
    grid = _grid(md_head, md_rows, align) + foot
    latex = _latex_table(cols, headers, shown, bold, align, spans, notes)
    if any(c.align == "decimal" for c in cols):
        warnings.append("decimal alignment is shown as right alignment; with a fixed number of decimals it "
                        "lines up exactly")
    return BuiltTable(markdown, grid, latex, list(dict.fromkeys(warnings)), caption, notes)


# -- files -----------------------------------------------------------------------------


def _md_path(project, id: str) -> Path:
    raw = (id or "").strip().replace("\\", "/")
    folder = project.root / objects.KINDS["tbl"][0]
    prefix = objects.KINDS["tbl"][1]
    if "/" in raw and raw.rsplit("/", 1)[0] != objects.KINDS["tbl"][0]:
        raise ValueError(f"no such table: {id}")
    name = raw.rsplit("/", 1)[-1]
    if name.endswith(".md"):
        name = name[:-3]
    candidates = []
    if raw.startswith("tbl:"):
        candidates.append(raw[4:])
    elif "/" in raw or raw.endswith(".md"):
        candidates.append(name[len(prefix):] if name.startswith(prefix) else name)
    else:
        candidates += [raw, raw[len(prefix):] if raw.startswith(prefix) else raw]
    for label in candidates:
        if objects._LABEL_RE.match(label or "") and (folder / f"{prefix}{label}.md").is_file():
            return folder / f"{prefix}{label}.md"
    raise ValueError(f"no such table: {id}")


def _source(project, id: str):
    if project.mode != "research":
        raise ValueError("generated tables are a research-project feature")
    md = _md_path(project, id)
    meta, body = objects._split(md.read_text(encoding="utf-8"))
    if meta.get("source") != "data":
        raise ValueError("this table is not built from data")
    csv_path = objects.safe_project_path(project, str(meta.get("data") or ""))
    if csv_path.suffix.lower() != ".csv":
        raise ValueError("a table's data is a .csv file")
    try:
        size = csv_path.stat().st_size
    except OSError:
        raise FileNotFoundError(f"the table's data file is missing: {meta.get('data')}") from None
    if size > MAX_CSV_BYTES:
        raise ValueError("the CSV is larger than 5 MB")
    return md, meta, body, csv_path


def build_table(project, id: str) -> BuiltTable:
    """Build a ``source: data`` table from its CSV and ``format:`` spec. Read-only: nothing is written (see
    ``apply_table``). ValueError / FileNotFoundError with a message in plain words."""
    _md, meta, _body, csv_path = _source(project, id)
    return format_csv(csv_path.read_text(encoding="utf-8-sig"), meta.get("format"), str(meta.get("caption") or ""))


def _format_sha(meta: dict) -> str:
    return hashlib.sha256(json.dumps(meta.get("format") or {}, sort_keys=True, default=str).encode()).hexdigest()


def apply_table(project, id: str) -> BuiltTable:
    """``build_table``, then write the note's body (marker comment + the Markdown form) and the ``built:``
    record (hashes of the data and the spec) that ``table_status`` compares. Everything else in the note's
    YAML is kept. The body is generated: hand edits to it are replaced."""
    md, meta, _body, csv_path = _source(project, id)
    built = format_csv(csv_path.read_text(encoding="utf-8-sig"), meta.get("format"), str(meta.get("caption") or ""))
    meta = dict(meta)
    meta["built"] = {"data_sha": hashlib.sha256(csv_path.read_bytes()).hexdigest(), "format_sha": _format_sha(meta)}
    head = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=10_000, default_flow_style=False)
    marker = MARKER.format(csv=str(meta.get("data")))
    objects._write(md, f"---\n{head}---\n{marker}\n\n{built.markdown}\n")
    return built


def table_status(project, id: str) -> ObjectStatus:
    """``current``, ``stale`` (the CSV or the spec changed since the last build, or it was never built),
    ``failed`` (the spec cannot be applied) or ``missing`` (no data file)."""
    try:
        _md, meta, _body, csv_path = _source(project, id)
    except FileNotFoundError:
        return "missing"
    try:
        build_table(project, id)
    except ValueError:
        return "failed"
    built = meta.get("built") if isinstance(meta.get("built"), dict) else {}
    same = (built.get("data_sha") == hashlib.sha256(csv_path.read_bytes()).hexdigest()
            and built.get("format_sha") == _format_sha(meta))
    return "current" if same else "stale"
